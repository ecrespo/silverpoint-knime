"""Writes the node modules from silverpoint's pinned host catalog (KN-DD-01, H-3): one module per
family under src/silverpoint_knime/nodes/, one node per chart a table can feed, each with a column
selector per role, the chart's options, the common view options and the appearance.

    uv run python scripts/make_nodes.py          # write
    uv run python scripts/make_nodes.py --check  # fail when a module differs from a fresh generation
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "silverpoint_knime" / "nodes"
VIEW = ("title", "description", "dataTable")
FAMILY_ORDER = [
    "bars",
    "lines",
    "areas",
    "points-grids",
    "radial",
    "distributions-comparisons",
    "hierarchies-dimensions",
    "flows",
    "fields-networks",
]


def catalog() -> dict:
    import silverpoint

    return silverpoint.catalog


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower().replace("-", "_")


def member(value: str) -> str:
    name = re.sub(r"\W", "_", value).upper()
    return name if name.isidentifier() and not keyword.iskeyword(name) else f"V_{name}"


def words(s: str) -> str:
    s = s.replace("-", " ").replace("_", " ")
    return s[:1].upper() + s[1:]


def plain(doc: str) -> str:
    return re.sub(r"\s*\(REQ-\d+(?:, REQ-\d+)*\)", "", doc.replace("`", "")).strip()


def enum_class(name: str, option: dict) -> str:
    lines = [f"class {name}(knext.EnumParameterOptions):"]
    for v in option["values"]:
        description = "The " + option["label"].lower() + " " + v + "."
        lines.append(f"    {member(v)} = ({words(v)!r}, {description!r})")
    return "\n".join(lines)


def option_parameter(var: str, option: dict, enums: list[str], enum_values: dict) -> str:
    label, doc = option["label"], plain(option["doc"]) or option["label"]
    if option["kind"] == "enum":
        cls = "".join(p.capitalize() for p in var.split("_")) + "Options"
        enums.append(enum_class(cls, option))
        enum_values[var] = {member(v): v for v in option["values"]}
        default = member(option.get("default", option["values"][0]))
        return f"{var} = knext.EnumParameter({label!r}, {doc!r}, {cls}.{default}.name, {cls})"
    if option["kind"] == "boolean":
        return f"{var} = knext.BoolParameter({label!r}, {doc!r}, {bool(option.get('default', False))!r})"
    if option["kind"] == "number":
        default = option.get("default")
        return f"{var} = knext.StringParameter({label!r}, {(doc + ' Empty: the chart default.')!r}, {('' if default is None else str(default))!r})"
    return f"{var} = knext.StringParameter({label!r}, {doc!r}, {str(option.get('default', ''))!r})"


def appearance_enums(cat: dict) -> str:
    substrates = list(dict.fromkeys(s["name"] for g in cat["appearance"]["grounds"] for s in g["substrates"]))
    labels = {s["name"]: s["label"] for g in cat["appearance"]["grounds"] for s in g["substrates"]}
    groups = {
        "Ground": [(g["name"], g["label"]) for g in cat["appearance"]["grounds"]],
        "Substrate": [(s, labels[s]) for s in substrates],
        "Mode": [(m["name"], m["label"]) for m in cat["appearance"]["modes"]],
        "Palette": [(p["name"], p["label"]) for p in cat["appearance"]["palettes"]],
    }
    out = []
    values = {}
    for title, items in groups.items():
        lines = [
            f"class {title}Options(knext.EnumParameterOptions):",
            '    DEFAULT = ("Default", "The ground\'s own choice.")',
        ]
        lines += [f"    {member(n)} = ({label!r}, {f'{title} {label}.'!r})" for n, label in items]
        out.append("\n".join(lines))
        values[title.lower()] = {member(n): n for n, _ in items}
    return "\n\n\n".join(out), values


def common_module(cat: dict) -> str:
    enums, values = appearance_enums(cat)
    return f'''"""Generated by scripts/make_nodes.py from host catalog {cat["version"]}. Do not edit (H-3)."""
# ruff: noqa
import knime.extension as knext

from ..base import DEFAULT_ROW_LIMIT, ROOT_CATEGORY

APPEARANCE_VALUES = {json.dumps(values)}


{enums}


class DataTableOptions(knext.EnumParameterOptions):
    HIDDEN = ("Hidden", "For assistive technology only.")
    VISIBLE = ("Visible", "Shown under the chart.")
    NONE = ("None", "No tabular alternative.")


def category(level_id, name):
    return knext.category(path=ROOT_CATEGORY, level_id=level_id, name=name, description=f"silverpoint charts: {{name.lower()}}.", icon="icons/silverpoint.png")


# Each node gets its own parameter objects; every parameter is controllable by a flow variable (KN-REQ-007).
def ground():
    return knext.EnumParameter("Ground", "The paper and ink (flow variable: ground).", GroundOptions.DEFAULT.name, GroundOptions)


def substrate():
    return knext.EnumParameter("Substrate", "The paper's tone.", SubstrateOptions.DEFAULT.name, SubstrateOptions)


def mode():
    return knext.EnumParameter("Mode", "Ink, or precision for high contrast (flow variable: mode).", ModeOptions.DEFAULT.name, ModeOptions)


def palette():
    return knext.EnumParameter("Palette", "The tones a series is drawn in (flow variable: palette).", PaletteOptions.DEFAULT.name, PaletteOptions)


def view_title():
    return knext.StringParameter("Title", "The chart's title and accessible name.", "")


def view_description():
    return knext.StringParameter("Description", "A long description for screen readers.", "")


def view_data_table():
    return knext.EnumParameter("Data table", "The tabular alternative.", DataTableOptions.HIDDEN.name, DataTableOptions)


def row_limit():
    return knext.IntParameter("Row limit", "Rows drawn; beyond it the node warns and draws the first rows.", DEFAULT_ROW_LIMIT, min_value=1, is_advanced=True)


def node_executable():
    return knext.StringParameter("Node.js executable", "Node.js 20+ for the SVG output; empty: node on PATH.", "", is_advanced=True)
'''


def node_source(chart: dict, family_label: str) -> str:
    cls = "".join(p.capitalize() for p in chart["slug"].split("-")) + "Node"
    roles = [*(r for r in chart["roles"] if r["required"]), *(r for r in chart["roles"] if not r["required"])]
    enums: list[str] = []
    enum_values: dict = {}
    params = []
    for r in roles:
        kind = "MultiColumnParameter" if r["multiple"] else "ColumnParameter"
        doc = f"The column{'s' if r['multiple'] else ''} for the {r['label'].lower()} role ({r['kind']}, {r['dataType']}){'' if r['required'] else '; optional'}."
        extra = "" if r["multiple"] else f", include_none_column={not r['required']}"
        params.append(
            f"role_{r['id']} = knext.{kind}({r['label']!r}, {doc!r}, column_filter=base.column_filter({r['dataType']!r}){extra})"
        )
    option_names = {}
    number_options = {}
    for o in chart["options"]:
        var = f"opt_{snake(o['name'])}"
        option_names[var] = o["name"]
        if o["kind"] == "number":
            number_options[var] = o["label"]
        params.append(option_parameter(var, o, enums, enum_values))
    option_names.update(
        {"view_title": "title", "view_description": "description", "view_data_table": "dataTable"}
    )
    enum_values["view_data_table"] = {"HIDDEN": "hidden", "VISIBLE": "visible", "NONE": "none"}
    role_tuple = ", ".join(
        f"base.Role({r['id']!r}, {r['label']!r}, {r['kind']!r}, {r['dataType']!r}, {r['required']}, {r['multiple']})"
        for r in roles
    )
    doc = (chart["summary"] or chart["title"]).replace('"""', "'''")
    body = "\n    ".join(params)
    return "\n\n\n".join(
        [
            *enums,
            f'''@knext.node(name={("Silverpoint " + chart["title"])!r}, node_type=knext.NodeType.VISUALIZER, icon_path="icons/silverpoint.png", category=CATEGORY, id={chart["slug"]!r}, keywords=["silverpoint", {family_label.lower()!r}, "chart"])
@knext.input_table("Table", "The rows to draw; one column per role.")
@knext.output_image("SVG", "The chart as SVG (with EB Garamond), when Node.js 20+ is available; otherwise a notice.")
@knext.output_view("Chart", "The chart: keyboard reading, a readout, the tabular alternative.")
class {cls}(base.ChartNode, knext.PythonNode):
    """{doc}

    silverpoint's {chart["title"].lower()} ({family_label.lower()}). Drawn by the silverpoint Python package, which carries the library's own script.
    """

    chart = {chart["slug"]!r}
    roles = ({role_tuple},)
    option_names = {option_names!r}
    number_options = {number_options!r}
    enum_values = {{**{enum_values!r}, **{{k: {{"DEFAULT": None, **v}} for k, v in _common.APPEARANCE_VALUES.items()}}}}
    {body}
    view_title = _common.view_title()
    view_description = _common.view_description()
    view_data_table = _common.view_data_table()
    ground = _common.ground()
    substrate = _common.substrate()
    mode = _common.mode()
    palette = _common.palette()
    row_limit = _common.row_limit()
    node_executable = _common.node_executable()''',
        ]
    )


def family_module(cat: dict, family: str, charts: list[dict]) -> str:
    label = words(family)
    header = f'''"""Generated by scripts/make_nodes.py from host catalog {cat["version"]}. Do not edit (H-3)."""
# ruff: noqa
import knime.extension as knext

from .. import base
from . import _common

CATEGORY = _common.category({family!r}, {label!r})
'''
    return header + "\n\n" + "\n\n\n".join(node_source(c, label) for c in charts) + "\n"


def outputs() -> dict[Path, str]:
    cat = catalog()
    charts = [c for c in cat["charts"] if c["binding"] != "none"]
    families = sorted({c["family"] for c in charts}, key=FAMILY_ORDER.index)
    files = {OUT / "_common.py": common_module(cat)}
    for family in families:
        files[OUT / f"{family.replace('-', '_')}.py"] = family_module(
            cat, family, [c for c in charts if c["family"] == family]
        )
    imports = "\n".join(f"from . import {f.replace('-', '_')}" for f in families)
    mapping = "\n".join(
        f"    {c['slug']!r}: {c['family'].replace('-', '_')}.{''.join(p.capitalize() for p in c['slug'].split('-'))}Node,"
        for c in charts
    )
    files[
        OUT / "__init__.py"
    ] = f'''"""Generated by scripts/make_nodes.py from host catalog {cat["version"]}. Do not edit (H-3)."""
# ruff: noqa
{imports}

ENGINE_VERSION = {cat["version"]!r}
FAMILIES = {json.dumps({f: words(f) for f in families})}
NODES = {{
{mapping}
}}
'''
    ruff = Path(sys.executable).parent / "ruff"
    for path, text in files.items():
        files[path] = subprocess.run(
            [str(ruff), "format", "--stdin-filename", str(path), "-"],
            input=text,
            capture_output=True,
            text=True,
            check=True,
            cwd=ROOT,
        ).stdout
    return files


def main() -> int:
    files = outputs()
    if "--check" in sys.argv:
        stale = [p.name for p, t in files.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        extra = [p.name for p in OUT.glob("*.py") if p not in files]
        if stale or extra:
            print("stale:", ", ".join(stale + extra), "— run `uv run python scripts/make_nodes.py`")
            return 1
        print(f"nodes current ({len(files) - 2} family modules)")
        return 0
    for p in OUT.glob("*.py"):
        p.unlink()
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} modules")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
